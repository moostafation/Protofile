"""Basic piping isometric drawings as DXF (one A3 sheet per line), using ezdxf.

Projection follows the usual piping-iso convention: North up-right at 30 deg,
East down-right at -30 deg, Up vertical. The drawing is scaled to fit the sheet
and dimensioned with TRUE lengths. This is a first, automatic iso: ISOGEN-level
layout (dimension de-cluttering, multi-sheet splitting, cut lists) is roadmap.
"""

from __future__ import annotations

import math
import re
from pathlib import Path

from ..connectivity import analyse
from ..geom import Vec3, format_enu
from ..model import ELBOW, FLANGE, GASKET, PIPE, TEE, VALVE, Pipeline, Project
from ..mto import material_takeoff

SHEET_W, SHEET_H = 420.0, 297.0  # A3 landscape, mm
DRAW_BOX = (15.0, 45.0, 285.0, 285.0)  # x0, y0, x1, y1 of the drawing area
C30 = math.cos(math.radians(30))


def iso_xy(p: Vec3) -> tuple[float, float]:
    return ((p.x + p.y) * C30, (p.y - p.x) * 0.5 + p.z)


def _require_ezdxf():
    try:
        import ezdxf  # noqa: F401
    except ImportError as exc:  # pragma: no cover - depends on environment
        raise ImportError("isometric DXF needs ezdxf: pip install ezdxf") from exc


class _Sheet:
    def __init__(self, line: Pipeline):
        pts = [iso_xy(p.position) for c in line.components for p in c.ports]
        xs, ys = [p[0] for p in pts], [p[1] for p in pts]
        self.minx, self.miny = min(xs), min(ys)
        w, h = (max(xs) - self.minx) or 1.0, (max(ys) - self.miny) or 1.0
        x0, y0, x1, y1 = DRAW_BOX
        self.scale = min((x1 - x0 - 40) / w, (y1 - y0 - 40) / h)
        self.ox = x0 + 20 + ((x1 - x0 - 40) - w * self.scale) / 2
        self.oy = y0 + 20 + ((y1 - y0 - 40) - h * self.scale) / 2

    def xy(self, p: Vec3) -> tuple[float, float]:
        x, y = iso_xy(p)
        return (self.ox + (x - self.minx) * self.scale, self.oy + (y - self.miny) * self.scale)


def _unit2(a, b):
    dx, dy = b[0] - a[0], b[1] - a[1]
    n = math.hypot(dx, dy) or 1.0
    return dx / n, dy / n


def line_isometric(project: Project, line: Pipeline):
    """Return an ezdxf document holding the isometric of one line."""
    _require_ezdxf()
    import ezdxf
    from ezdxf.enums import TextEntityAlignment

    doc = ezdxf.new("R2010", setup=True)
    doc.units = ezdxf.units.MM
    for name, color in (("PIPE", 7), ("SYMBOL", 1), ("DIM", 3), ("TEXT", 7), ("FRAME", 8), ("WELD", 2)):
        doc.layers.add(name, color=color)
    msp = doc.modelspace()
    sh = _Sheet(line)

    # Frame and title block
    msp.add_lwpolyline([(5, 5), (SHEET_W - 5, 5), (SHEET_W - 5, SHEET_H - 5), (5, SHEET_H - 5)], close=True, dxfattribs={"layer": "FRAME"})
    msp.add_lwpolyline([(5, 35), (SHEET_W - 5, 35)], dxfattribs={"layer": "FRAME"})
    msp.add_lwpolyline([(290, 35), (290, SHEET_H - 5)], dxfattribs={"layer": "FRAME"})

    def text(s, x, y, h=2.5, layer="TEXT", align=TextEntityAlignment.LEFT, rot=0.0):
        t = msp.add_text(s, height=h, rotation=rot, dxfattribs={"layer": layer, "style": "OpenSans"})
        t.set_placement((x, y), align=align)
        return t

    text(f"LINE {line.number}", 10, 24, 5)
    text(f"SPEC {line.spec}   NPS {line.nps}   {line.fluid}".strip(), 10, 15, 3)
    text(f"{project.name}   {project.area}   {project.unit}".strip(), 10, 9, 2.5)
    text("ISOMETRIC - NOT TO SCALE - GENERATED BY PLANTFORGE (PRELIMINARY, NOT FOR CONSTRUCTION)", 200, 9, 2.2)

    # North arrow (iso North = up-right)
    nx, ny = 265.0, 260.0
    ux, uy = C30, 0.5
    msp.add_line((nx, ny), (nx + 14 * ux, ny + 14 * uy), dxfattribs={"layer": "SYMBOL"})
    tip = (nx + 14 * ux, ny + 14 * uy)
    msp.add_solid([tip, (tip[0] - 3 * ux + 1.2 * uy, tip[1] - 3 * uy - 1.2 * ux), (tip[0] - 3 * ux - 1.2 * uy, tip[1] - 3 * uy + 1.2 * ux)], dxfattribs={"layer": "SYMBOL"})
    text("N", tip[0] + 2, tip[1] + 1, 3.5)

    conn = analyse(project)
    item_no: dict[str, int] = {}
    mto = material_takeoff(project, lines=[line.number], conn=conn)
    for n, row in enumerate(mto.rows, 1):
        item_no[(row.kind, row.nps, row.description)] = n

    # Components
    for c in line.components:
        pa, pb = sh.xy(c.ports[0].position), sh.xy(c.ports[1].position)
        if c.kind == PIPE:
            msp.add_line(pa, pb, dxfattribs={"layer": "PIPE", "lineweight": 50})
            mid = ((pa[0] + pb[0]) / 2, (pa[1] + pb[1]) / 2)
            n = item_no.get((PIPE, c.nps, c.description))
            if n and c.props["length"] > 300:
                _balloon(msp, text, mid, n)
        elif c.kind == ELBOW:
            v = sh.xy(c.props["vertex"])
            msp.add_lwpolyline([pa, v, pb], dxfattribs={"layer": "PIPE", "lineweight": 50})
        elif c.kind == TEE:
            ctr, br = sh.xy(c.props["center"]), sh.xy(c.port("BR").position)
            msp.add_line(pa, pb, dxfattribs={"layer": "PIPE", "lineweight": 50})
            msp.add_line(ctr, br, dxfattribs={"layer": "PIPE", "lineweight": 50})
        elif c.kind == FLANGE:
            face = sh.xy(c.port("FACE").position)
            ux_, uy_ = _unit2(pa, pb)
            px, py = -uy_ * 3.0, ux_ * 3.0
            msp.add_line(pa, pb, dxfattribs={"layer": "PIPE", "lineweight": 50})
            msp.add_line((face[0] - px, face[1] - py), (face[0] + px, face[1] + py), dxfattribs={"layer": "SYMBOL"})
        elif c.kind == GASKET:
            continue
        elif c.kind == VALVE:
            ux_, uy_ = _unit2(pa, pb)
            px, py = -uy_ * 3.0, ux_ * 3.0
            ctr = ((pa[0] + pb[0]) / 2, (pa[1] + pb[1]) / 2)
            msp.add_lwpolyline(
                [(pa[0] + px, pa[1] + py), (pb[0] - px, pb[1] - py), (pb[0] + px, pb[1] + py), (pa[0] - px, pa[1] - py)],
                close=True,
                dxfattribs={"layer": "SYMBOL"},
            )
            text(f"{c.tag} {c.props['valve_type'].upper()}", ctr[0] + px * 2 + 1, ctr[1] + py * 2 + 1, 2.2)
            n = item_no.get((VALVE, c.nps, c.description))
            if n:
                _balloon(msp, text, (ctr[0] - px * 3, ctr[1] - py * 3), n)

    # Butt welds
    for j in conn.welds:
        if j.a.group == line.number or j.b.group == line.number:
            msp.add_circle(sh.xy(j.pa.position), 0.8, dxfattribs={"layer": "WELD"})

    # True-length dimensions along every straight leg
    stations = _key_points(line)
    for a, b in zip(stations, stations[1:]):
        length = (b - a).length()
        if length < 1.0:
            continue
        p1, p2 = sh.xy(a), sh.xy(b)
        ux_, uy_ = _unit2(p1, p2)
        offset = (-uy_ * 7.0, ux_ * 7.0)
        d1 = (p1[0] + offset[0], p1[1] + offset[1])
        d2 = (p2[0] + offset[0], p2[1] + offset[1])
        msp.add_line(p1, d1, dxfattribs={"layer": "DIM"})
        msp.add_line(p2, d2, dxfattribs={"layer": "DIM"})
        msp.add_line(d1, d2, dxfattribs={"layer": "DIM"})
        for q in (d1, d2):
            msp.add_line((q[0] - 1.0, q[1] - 1.0), (q[0] + 1.0, q[1] + 1.0), dxfattribs={"layer": "DIM"})
        mid = ((d1[0] + d2[0]) / 2 + offset[0] * 0.25, (d1[1] + d2[1]) / 2 + offset[1] * 0.25)
        angle = math.degrees(math.atan2(uy_, ux_))
        if angle > 90 or angle < -90:
            angle += 180
        text(f"{length:.0f}", mid[0], mid[1], 2.5, layer="DIM", align=TextEntityAlignment.MIDDLE_CENTER, rot=angle)

    # End coordinates
    for end, ref in ((line.points[0], line.start_ref), (line.points[-1], line.end_ref)):
        x, y = sh.xy(end)
        label = format_enu(end) + (f"  ({ref})" if ref else "")
        text(label, x + 3, y - 5, 2.2)

    # Bill of materials
    y = SHEET_H - 14
    text("BILL OF MATERIALS", 295, y, 3.5)
    y -= 7
    text("PT  QTY      NPS  DESCRIPTION", 295, y, 2.2)
    for n, row in enumerate(mto.rows, 1):
        y -= 5
        qty = f"{row.quantity:.1f}m" if row.unit == "m" else f"{row.quantity:.0f}"
        desc = row.description if len(row.description) <= 48 else row.description[:47] + "..."
        text(f"{n:<3} {qty:<8} {row.nps:>5}  {desc}", 295, y, 1.9)
        if y < 50:
            break
    text(f"BUTT WELDS: {mto.weld_count}  ({mto.weld_inch_dia:g} INCH-DIA)", 295, 40, 2.2)
    return doc


def _balloon(msp, text, at, n):
    from ezdxf.enums import TextEntityAlignment

    msp.add_circle(at, 2.6, dxfattribs={"layer": "TEXT"})
    text(str(n), at[0], at[1], 2.4, align=TextEntityAlignment.MIDDLE_CENTER)


def _key_points(line: Pipeline) -> list[Vec3]:
    """Route start, every elbow intersection point, inline item centres and route end, in flow order."""
    pts = [line.points[0]]
    for c in line.components:
        if c.kind == ELBOW:
            pts.append(c.props["vertex"])
        elif c.kind == VALVE:
            pts.append((c.ports[0].position + c.ports[1].position) * 0.5)
        elif c.kind == TEE:
            pts.append(c.props["center"])
    pts.append(line.points[-1])
    return pts


def write_isometrics(project: Project, folder: str | Path) -> list[Path]:
    out = Path(folder)
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for number, line in project.lines.items():
        path = out / f"{re.sub(r'[^A-Za-z0-9._-]+', '_', number.replace(chr(34), 'in')).strip('_')}.dxf"
        line_isometric(project, line).saveas(path)
        written.append(path)
    return written
