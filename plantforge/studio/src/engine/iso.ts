// Automatic piping isometric for one line: projection, symbols, chained true-length dimensions,
// elevations, connection notes, BOM balloons, bill of materials and title block on an A3 sheet.

import type { LineResult, Model } from "./compute";
import { Drawing, P2, Prim } from "./drawing";
import { materialTakeoff } from "./mto";
import { npsValue } from "./catalog";
import { V3, dist, dot, fmtENU } from "./vec";

const W = 420;
const H = 297;
const AREA = { x0: 14, y0: 42, x1: 286, y1: 286 };
const C30 = Math.cos(Math.PI / 6);

export const isoXY = (p: V3): P2 => [(p[0] + p[1]) * C30, (p[1] - p[0]) * 0.5 + p[2]];

const sub2 = (a: P2, b: P2): P2 => [a[0] - b[0], a[1] - b[1]];
const add2 = (a: P2, b: P2): P2 => [a[0] + b[0], a[1] + b[1]];
const mul2 = (a: P2, k: number): P2 => [a[0] * k, a[1] * k];
const len2 = (a: P2) => Math.hypot(a[0], a[1]);
const unit2 = (a: P2): P2 => {
  const l = len2(a) || 1;
  return [a[0] / l, a[1] / l];
};
const perp2 = (a: P2): P2 => [-a[1], a[0]];

function wrap(s: string, n: number): string[] {
  const words = s.split(" ");
  const out: string[] = [];
  let cur = "";
  for (const w of words) {
    if ((cur + " " + w).trim().length > n) {
      if (cur) out.push(cur);
      cur = w;
    } else cur = (cur + " " + w).trim();
  }
  if (cur) out.push(cur);
  return out;
}

function endLabel(model: Model, line: LineResult, which: "start" | "end"): string {
  const ref = line.doc[which];
  const word = which === "start" ? "FROM" : "TO";
  if (ref.kind === "nozzle") {
    const eq = model.equipment.get(ref.eq);
    return `${word} ${eq?.doc.tag ?? "?"}/${ref.nozzle}`;
  }
  if (ref.kind === "tee") return `${word} ${model.lines.get(ref.line)?.doc.number ?? "?"} (TEE)`;
  return ref.kind === "flanged" ? "BATTERY LIMIT - FLANGED END" : "OPEN END";
}

export function lineIsometric(model: Model, lineId: string, date = new Date().toISOString().slice(0, 10)): Drawing {
  const line = model.lines.get(lineId);
  if (!line) throw new Error("line not found");
  const prims: Prim[] = [];
  const L = (a: P2, b: P2, layer: string, w?: number) => prims.push({ t: "line", a, b, layer, w });
  const T = (p: P2, s: string, h: number, layer = "TEXT", rot = 0, anchor: "start" | "middle" | "end" = "start", bold = false) =>
    prims.push({ t: "text", p, s, h, layer, rot, anchor, bold });

  // ---- sheet frame and title block -------------------------------------------
  prims.push({ t: "poly", pts: [[5, 5], [W - 5, 5], [W - 5, H - 5], [5, H - 5]], closed: true, layer: "FRAME" });
  L([5, 36], [W - 5, 36], "FRAME");
  L([289, 36], [289, H - 5], "FRAME");
  const p = model.doc.project;
  T([10, 24], `LINE ${line.doc.number}`, 6, "TEXT", 0, "start", true);
  T([10, 16], `SPEC ${line.doc.spec}   NPS ${line.doc.nps}   ${line.doc.fluid.toUpperCase()}`, 3);
  T([10, 9.5], `${p.name}  |  ${p.plant}  |  ${p.area}  |  ${p.unit}`.toUpperCase(), 2.2);
  const tb = [
    ["SHEET", "1 OF 1"],
    ["REV", "A"],
    ["DATE", date],
    ["STATUS", "PRELIMINARY - NOT FOR CONSTRUCTION"],
  ];
  let tx = 200;
  for (const [k, v] of tb) {
    L([tx - 3, 5], [tx - 3, 36], "FRAME");
    T([tx, 28], k, 1.8, "NOTE");
    T([tx, 21], v, 2.2);
    tx += k === "STATUS" ? 0 : 30;
  }
  T([W - 8, 9], "GENERATED BY PLANTFORGE STUDIO", 1.8, "NOTE", 0, "end");

  if (!line.comps.length) {
    T([150, 160], line.error ?? "Line has no components.", 3.5, "NOTE", 0, "middle");
    return { title: line.doc.number, width: W, height: H, prims };
  }

  // ---- projection fit ------------------------------------------------------------
  const pts3: V3[] = [];
  for (const c of line.comps) {
    for (const q of c.ports) pts3.push(q.pos);
    if (c.kind === "ELBOW") pts3.push(c.props.vertex);
  }
  const xy = pts3.map(isoXY);
  const minX = Math.min(...xy.map((q) => q[0]));
  const maxX = Math.max(...xy.map((q) => q[0]));
  const minY = Math.min(...xy.map((q) => q[1]));
  const maxY = Math.max(...xy.map((q) => q[1]));
  const margin = 28;
  const s = Math.min((AREA.x1 - AREA.x0 - 2 * margin) / Math.max(maxX - minX, 1), (AREA.y1 - AREA.y0 - 2 * margin) / Math.max(maxY - minY, 1), 0.06);
  const ox = AREA.x0 + margin + (AREA.x1 - AREA.x0 - 2 * margin - (maxX - minX) * s) / 2;
  const oy = AREA.y0 + margin + (AREA.y1 - AREA.y0 - 2 * margin - (maxY - minY) * s) / 2;
  const P = (q: V3): P2 => {
    const r = isoXY(q);
    return [ox + (r[0] - minX) * s, oy + (r[1] - minY) * s];
  };
  const centroid: P2 = [ox + ((maxX - minX) * s) / 2, oy + ((maxY - minY) * s) / 2];

  // ---- components ------------------------------------------------------------------
  const rows = materialTakeoff([{ spec: line.doc.spec, comps: line.comps }]);
  const rowOf = (desc: string, kind: string, nps: string) => rows.findIndex((r) => r.description === desc && r.kind === kind && r.nps === nps) + 1;
  const balloon = (at: P2, dir: P2, n: number) => {
    if (n <= 0) return;
    const off = perp2(unit2(dir));
    const side = dot([off[0], off[1], 0], [at[0] - centroid[0], at[1] - centroid[1], 0]) >= 0 ? 1 : -1;
    const c = add2(at, mul2(off, 7 * side));
    L(at, add2(at, mul2(off, 4.6 * side)), "TEXT");
    prims.push({ t: "circle", c, r: 2.4, layer: "TEXT" });
    T([c[0], c[1] - 0.8], String(n), 2.2, "TEXT", 0, "middle");
  };

  for (const c of line.comps) {
    const a = c.ports[0] ? P(c.ports[0].pos) : null;
    const b = c.ports[1] ? P(c.ports[1].pos) : null;
    switch (c.kind) {
      case "PIPE":
        L(a!, b!, "PIPE", 0.7);
        if (c.props.length > 700) balloon(mul2(add2(a!, b!), 0.5), sub2(b!, a!), rowOf(c.desc, "PIPE", c.nps));
        break;
      case "ELBOW":
        prims.push({ t: "poly", pts: [a!, P(c.props.vertex), b!], layer: "PIPE", w: 0.7 });
        break;
      case "TEE": {
        L(a!, b!, "PIPE", 0.7);
        const br = P(c.ports[2].pos);
        L(P(c.props.center), br, "PIPE", 0.7);
        const branches = [...model.lines.values()].filter((l) => l.doc.start.kind === "tee" && l.doc.start.line === line.doc.id && l.doc.start.item === c.props.inlineId);
        for (const bl of branches) T(add2(br, [1.5, 1.5]), `CONT. ON ${bl.doc.number}`, 2, "NOTE");
        balloon(P(c.props.center), sub2(b!, a!), rowOf(c.desc, "TEE", c.nps));
        break;
      }
      case "FLANGE": {
        L(a!, b!, "PIPE", 0.7);
        const face = P(c.ports[1].pos);
        const n = mul2(perp2(unit2(sub2(b!, a!))), 2.4);
        L(sub2(face, n), add2(face, n), "SYMBOL", 0.5);
        break;
      }
      case "VALVE": {
        const u = unit2(sub2(b!, a!));
        const n = mul2(perp2(u), 2.4);
        const mid = mul2(add2(a!, b!), 0.5);
        const l2 = Math.max(len2(sub2(b!, a!)), 3.2);
        const aa = sub2(mid, mul2(u, l2 / 2));
        const bb = add2(mid, mul2(u, l2 / 2));
        prims.push({ t: "poly", pts: [add2(aa, n), sub2(bb, n), add2(bb, n), sub2(aa, n)], closed: true, layer: "SYMBOL", w: 0.35 });
        if (c.props.valveType === "check") prims.push({ t: "poly", pts: [add2(mid, mul2(u, 1.2)), add2(sub2(mid, mul2(u, 0.6)), mul2(n, 0.4)), sub2(sub2(mid, mul2(u, 0.6)), mul2(n, 0.4))], fill: true, layer: "SYMBOL" });
        else {
          const st = isoXY(c.props.stem as V3);
          const sd = unit2(st);
          const top = add2(mid, mul2(sd, 4));
          L(mid, top, "SYMBOL", 0.35);
          L(sub2(top, mul2(perp2(sd), 1.6)), add2(top, mul2(perp2(sd), 1.6)), "SYMBOL", 0.35);
        }
        T(add2(mid, mul2(perp2(u), -4.5)), `${c.tag} ${String(c.props.valveType).toUpperCase()}`, 1.9, "NOTE", 0, "middle");
        balloon(mid, sub2(b!, a!), rowOf(c.desc, "VALVE", c.nps));
        break;
      }
      case "SUPPORT": {
        const q = P(c.props.at);
        prims.push({ t: "poly", pts: [[q[0], q[1] - 0.6], [q[0] - 1.6, q[1] - 3.2], [q[0] + 1.6, q[1] - 3.2]], closed: true, layer: "SUPPORT" });
        T([q[0] + 2, q[1] - 3.4], c.tag, 1.6, "SUPPORT");
        break;
      }
    }
  }

  // ---- welds -------------------------------------------------------------------------
  for (const j of model.conn.welds) {
    if (j.a.owner.id !== line.doc.id && j.b.owner.id !== line.doc.id) continue;
    prims.push({ t: "circle", c: P(j.pa.pos), r: 0.75, fill: true, layer: "WELD" });
  }

  // ---- dimensions (true lengths) and elevations -----------------------------------------
  const centers: { leg: number; s: number }[] = [];
  for (const c of line.comps) {
    if (c.kind !== "VALVE" && c.kind !== "TEE") continue;
    const at3: V3 = c.props.center;
    line.legs.forEach((lg, k) => {
      const s0 = dot([at3[0] - lg.start[0], at3[1] - lg.start[1], at3[2] - lg.start[2]], lg.dir);
      const off = dist(at3, [lg.start[0] + lg.dir[0] * s0, lg.start[1] + lg.dir[1] * s0, lg.start[2] + lg.dir[2] * s0]);
      if (off < 1 && s0 > 0 && s0 < lg.length) centers.push({ leg: k, s: s0 });
    });
  }
  line.legs.forEach((lg, k) => {
    const stations = [0, ...centers.filter((c) => c.leg === k).map((c) => c.s).sort((x, y) => x - y), lg.length];
    const a2 = P(lg.start);
    const b2 = P(lg.end);
    const u = unit2(sub2(b2, a2));
    let n = perp2(u);
    const mid2 = mul2(add2(a2, b2), 0.5);
    if (n[0] * (mid2[0] - centroid[0]) + n[1] * (mid2[1] - centroid[1]) < 0) n = mul2(n, -1);
    const off = mul2(n, 7);
    for (let i = 1; i < stations.length; i++) {
      const l3 = stations[i] - stations[i - 1];
      if (l3 < 1) continue;
      const pa = add2(a2, mul2(sub2(b2, a2), stations[i - 1] / lg.length));
      const pb = add2(a2, mul2(sub2(b2, a2), stations[i] / lg.length));
      const da = add2(pa, off);
      const db = add2(pb, off);
      L(add2(pa, mul2(n, 1.2)), add2(da, mul2(n, 1)), "DIM", 0.18);
      L(add2(pb, mul2(n, 1.2)), add2(db, mul2(n, 1)), "DIM", 0.18);
      L(da, db, "DIM", 0.18);
      const tick = mul2(unit2(add2(u, n)), 1.1);
      L(sub2(da, tick), add2(da, tick), "DIM", 0.3);
      L(sub2(db, tick), add2(db, tick), "DIM", 0.3);
      let rot = (Math.atan2(u[1], u[0]) * 180) / Math.PI;
      if (rot > 90.5) rot -= 180;
      if (rot < -89.5) rot += 180;
      T(add2(mul2(add2(da, db), 0.5), mul2(n, 1.1)), `${Math.round(l3)}`, 2.3, "DIM", rot, "middle");
    }
    if (Math.abs(lg.dir[2]) < 1e-6) {
      const pos = add2(mid2, mul2(n, -5.5));
      let rot = (Math.atan2(u[1], u[0]) * 180) / Math.PI;
      if (rot > 90.5) rot -= 180;
      if (rot < -89.5) rot += 180;
      T(pos, `EL +${Math.round(lg.start[2])}`, 2, "NOTE", rot, "middle");
    }
  });

  // ---- ends ----------------------------------------------------------------------------
  const ends: [V3, string][] = [
    [line.path[0], endLabel(model, line, "start")],
    [line.path[line.path.length - 1], endLabel(model, line, "end")],
  ];
  for (const [q3, label] of ends) {
    const q = P(q3);
    const right = q[0] < centroid[0] ? -1 : 1;
    const anchor = right > 0 ? "start" : "end";
    T([q[0] + right * 4, q[1] + 3.5], label, 2.4, "TEXT", 0, anchor, true);
    T([q[0] + right * 4, q[1] - 0.2], fmtENU(q3), 2, "NOTE", 0, anchor);
  }

  // ---- north arrow --------------------------------------------------------------------------
  const na: P2 = [262, 268];
  const nd: P2 = [C30, 0.5];
  const tip = add2(na, mul2(nd, 13));
  L(na, tip, "SYMBOL", 0.4);
  prims.push({ t: "poly", pts: [tip, add2(sub2(tip, mul2(nd, 3.2)), mul2(perp2(nd), 1.3)), sub2(sub2(tip, mul2(nd, 3.2)), mul2(perp2(nd), 1.3))], fill: true, layer: "SYMBOL" });
  T(add2(tip, [1.5, 1]), "N", 3.5, "TEXT", 0, "start", true);

  // ---- bill of materials ---------------------------------------------------------------------
  let y = H - 13;
  T([293, y], "BILL OF MATERIALS", 3.2, "TEXT", 0, "start", true);
  y -= 6.5;
  T([293, y], "PT", 1.8, "NOTE");
  T([300, y], "QTY", 1.8, "NOTE");
  T([316, y], "NPS", 1.8, "NOTE", 0, "end");
  T([319, y], "DESCRIPTION", 1.8, "NOTE");
  L([292, y - 1.4], [W - 7, y - 1.4], "FRAME");
  y -= 5;
  rows.forEach((r, i) => {
    if (y < 60) return;
    const qty = r.unit === "m" ? `${r.qty.toFixed(1)}M` : `${r.qty}`;
    T([293, y], String(i + 1), 1.8);
    T([300, y], qty, 1.8);
    T([316, y], r.nps, 1.8, "TEXT", 0, "end");
    const lines = wrap(r.description, 46);
    lines.forEach((ln, k) => T([319, y - k * 2.7], ln, 1.6));
    y -= Math.max(1, lines.length) * 2.7 + 1.6;
  });
  const welds = model.conn.welds.filter((j) => j.a.owner.id === line.doc.id || j.b.owner.id === line.doc.id);
  const inch = welds.reduce((t, j) => t + npsValue(j.pa.nps), 0);
  const weight = line.comps.filter((c) => c.kind === "PIPE").reduce((t, c) => t + c.props.weight, 0);
  L([292, 52], [W - 7, 52], "FRAME");
  T([293, 47], `BUTT WELDS: ${welds.length}  (${+inch.toFixed(2)} INCH-DIA)`, 2);
  T([293, 43], `PIPE: ${(line.pipeLength / 1000).toFixed(2)} M  /  ${weight.toFixed(0)} KG`, 2);
  T([293, 39], `SHOES: ${line.comps.filter((c) => c.kind === "SUPPORT").length}`, 2);

  return { title: line.doc.number, width: W, height: H, prims };
}
